def apply_dryfruits_500g_bundle(
    session: Session,
    household_id: int,
    list_id: int,
    now_dt: datetime,
) -> int:
    existing_custom = {
        cl.listing_id
        for cl in session.exec(select(CustomListing).where(CustomListing.household_id == household_id)).all()
    }

    for (
        lid,
        pkey,
        fkey,
        cat,
        title,
        brand,
        pack,
        plat,
        listed,
        mrp,
        member,
        eta,
        url,
        icon,
    ) in DRYFRUITS_500G_LISTINGS:
        if lid not in existing_custom:
            session.add(
                CustomListing(
                    household_id=household_id,
                    listing_id=lid,
                    platform=plat,
                    sku=lid,
                    url=url,
                    product_key=pkey,
                    family_key=fkey,
                    category=cat,
                    title=title,
                    brand=brand,
                    pack_label=pack,
                    icon=icon,
                )
            )
            session.add(
                PriceObservation(
                    household_id=household_id,
                    listing_id=lid,
                    listed_paise=listed,
                    mrp_paise=mrp,
                    member_price_paise=member,
                    in_stock=True,
                    eta_minutes=eta,
                    source="extension",
                    observed_at=now_dt,
                )
            )

    existing_offers = {
        off.code
        for off in session.exec(
            select(Offer).where(
                Offer.household_id == household_id,
                Offer.archived.is_(False),  # type: ignore[attr-defined]
            )
        ).all()
    }
    for code, plat, min_order, val, uses, vtype in DRYFRUITS_DEFAULT_OFFERS:
        if code not in existing_offers:
            session.add(
                Offer(
                    household_id=household_id,
                    code=code,
                    platform=plat,
                    kind="flat",
                    min_order_paise=min_order,
                    value_paise=val,
                    uses_left=uses,
                    value_type=vtype,
                )
            )

    existing_needs = {n.line_id for n in session.exec(select(Need).where(Need.list_id == list_id)).all()}
    added_needs = 0
    for line_id, family_key, quantity in DRYFRUITS_500G_NEEDS:
        if line_id not in existing_needs:
            session.add(
                Need(
                    list_id=list_id,
                    line_id=line_id,
                    product_key=None,
                    family_key=family_key,
                    quantity=quantity,
                    qty=1,
                    status="open",
                )
            )
            added_needs += 1

    session.commit()
    return added_needs
